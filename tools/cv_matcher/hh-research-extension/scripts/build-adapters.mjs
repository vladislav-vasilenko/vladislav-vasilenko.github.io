import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

export const extensionRoot = fileURLToPath(new URL('../', import.meta.url));
const selectorKeys = ['description', 'card', 'listingTitle', 'linkSelector'];

export function validateDefinitions(definitions) {
  const ids = new Set(), hosts = new Set();
  if (!definitions.length) throw Error('Adapter catalog is empty');
  for (const adapter of definitions) {
    const fail = message => { throw Error(`${adapter.id || 'adapter'}: ${message}`); };
    if (!/^[a-z][a-z0-9-]*$/.test(adapter.id) || ids.has(adapter.id)) fail('invalid or duplicate id');
    ids.add(adapter.id);
    if (typeof adapter.label !== 'string' || !adapter.label.trim()) fail('label is required');
    if (!Array.isArray(adapter.hosts) || !adapter.hosts.length) fail('hosts are required');
    for (const host of adapter.hosts) {
      if (!/^(?:[a-z0-9-]+\.)+[a-z]{2,}$/.test(host) || hosts.has(host)) fail('invalid or duplicate host');
      hosts.add(host);
    }
    const url = new URL(adapter.url);
    if (url.protocol !== 'https:' || url.username || url.password || url.port || !adapter.hosts.includes(url.hostname)) fail('home must be HTTPS on a declared host');
    if (typeof adapter.pages !== 'string' || !adapter.pages.length) fail('pages pattern is required');
    new RegExp(adapter.pages);
    const checkSelectors = value => {
      for (const key of selectorKeys) if (key in value && (typeof value[key] !== 'string' || !value[key].trim())) fail(`empty selector: ${key}`);
    };
    checkSelectors(adapter);
    for (const [host, layout] of Object.entries(adapter.layouts || {})) {
      if (!adapter.hosts.includes(host)) fail('layout must use a declared host');
      checkSelectors(layout);
    }
  }
  return definitions;
}

export function buildAdapters(root = extensionRoot) {
  const directory = path.join(root, 'adapters');
  const definitions = fs.readdirSync(directory).filter(name => name.endsWith('.json')).sort()
    .map(name => JSON.parse(fs.readFileSync(path.join(directory, name), 'utf8')));
  validateDefinitions(definitions);
  const runtime = fs.readFileSync(path.join(directory, 'runtime.js'), 'utf8').trimEnd();
  return '// Generated by node scripts/build-adapters.mjs. Edit adapters/*.json or adapters/runtime.js.\n'
    + runtime + '\ninstallJobBoardAdapters(globalThis, ' + JSON.stringify(definitions, null, 2) + ');\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const output = path.join(extensionRoot, 'board-adapters.js'), expected = buildAdapters();
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== expected) {
      console.error('Adapter bundle is stale. Run node scripts/build-adapters.mjs.');
      process.exitCode = 1;
    } else console.log('Adapter bundle is current.');
  } else {
    fs.writeFileSync(output, expected);
    console.log('Built board-adapters.js');
  }
}
