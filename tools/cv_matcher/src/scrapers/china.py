from ._base import BaseScraper,_launch_browser
from ..china_sources import CHINA_SOURCES
from ..board_import import identity
from ..vacancy_locations import normalize_locations


def clean(value):
    return BeautifulSoup(value,'html.parser').get_text('\n',strip=True) if isinstance(value,str) else ''


def row(source,link,title,description,locations,*,full=True):
    own=identity(link)
    if not own or not title or len(description)>100000:return None
    result={**own,'company':CHINA_SOURCES[source]['label'],'title':title.strip(),'description':description.strip(),
      'description_quality':'full' if full and len(description.strip())>=150 else 'snippet',
      'locations':list(dict.fromkeys(x.strip() for x in locations if isinstance(x,str) and x.strip())),
      'source_page':link,'description_fetched_at':datetime.now(timezone.utc).isoformat(),'origin_query':'','pub_date':'Recently'}
    return normalize_locations(result)


def parse_feed(source,body,base):
    """Recognized contracts only; unrelated telemetry/facets are never job records."""
    provider=CHINA_SOURCES[source]['provider'];result=[]
    if provider=='feishu':
        if body.get('code')!=0 or not isinstance(body.get('data'),dict):raise ValueError('Feishu: неизвестный ответ выдачи.')
        data=body['data'];items=data.get('job_post_list');total=data.get('count')
        if not isinstance(items,list):raise ValueError('Feishu: список вакансий не распознан.')
        for j in items:
            if not isinstance(j,dict) or not re.fullmatch(r'\d{1,25}',str(j.get('id',''))):continue
            path='/experienced/position/'+str(j['id'])+'/detail' if source=='bytedance' else '/index/position/'+str(j['id'])+'/detail'
            url=urlsplit(base)._replace(path=path,query='',fragment='').geturl()
            cities=j.get('city_list') or ([j['city_info']] if j.get('city_info') else [])
            locations=[c.get('en_name') or c.get('name') for c in cities if isinstance(c,dict)]
            desc='\n\n'.join(v for v in [clean(j.get('description')),clean(j.get('requirement'))] if v)
            r=row(source,url,j.get('title',''),desc,locations,full=bool(j.get('description') and j.get('requirement')))
            if r:result.append(r)
    elif provider=='kuaishou':
        if body.get('code')!=0 or not isinstance(body.get('result'),dict):raise ValueError('Kuaishou: неизвестный ответ выдачи.')
        data=body['result'];items=data.get('list');total=data.get('total')
        if not isinstance(items,list):raise ValueError('Kuaishou: список вакансий не распознан.')
        for j in items:
            if not isinstance(j,dict) or type(j.get('id')) is not int:continue
            locations=j.get('workLocationsCode') or [j.get('workLocationCode','')]
            if not isinstance(locations,list):locations=[]
            desc='\n\n'.join(v for v in [clean(j.get('description')),clean(j.get('positionDemand'))] if v)
            r=row(source,'https://zhaopin.kuaishou.cn/#/official/social/job-info/'+str(j['id']),j.get('name',''),desc,locations,full=bool(j.get('description') and j.get('positionDemand')))
            if r:result.append(r)
    else:raise ValueError('Нет распознанного JSON-контракта.')
    return result,total if type(total) is int and total>=0 else None


def moka_detail(html,url):
    """Visible title and description on current Moka portal; exclude navigation."""
    soup=BeautifulSoup(html,'html.parser');title=soup.select_one('[class*="title-"][class*="heading"],h1,[class*="job-title"]')
    label=soup.find(string=lambda s:s and s.strip()=='职位描述')
    body=label.parent.parent.parent if label else None
    locations=[]
    for label in soup.find_all(string=lambda s:s and s.strip()=='工作地点'):
        node=label.parent
        for _ in range(4):
            if node is None:break
            text=node.get_text(' ',strip=True)
            value=re.sub(r'^(工作地点\s*)+','',text).strip()
            if value and len(value)<500:locations=[value];break
            node=node.parent
        if locations:break
    return {'title':title.get_text(' ',strip=True) if title else '', 'description':body.get_text('\n',strip=True) if body else '', 'locations':locations}


class ChinaScraper(BaseScraper):
    source_key=''

    def fetch_jobs(self,query='',existing_ids=None):
        if not self.source_key:raise ValueError('Не выбран источник.')
        self.report={'listed':0,'accepted':0,'errors':0,'coverage':'partial'}
        self._existing=set(existing_ids or ());self._query=query.strip().lower()
        self._emit('source_start',company=self.company_name,query=query,limit=self.limit)
        print(self.company_name+': public collection started',flush=True)
        provider=CHINA_SOURCES[self.source_key]['provider']
        try:
            rows=self._tencent() if provider=='tencent' else self._kuaishou() if provider=='kuaishou' else self._browser()
            self.report['accepted']=len(rows);self._emit('source_done',company=self.company_name,count=len(rows),report=self.report)
            print(self.company_name+': '+str(len(rows))+' accepted; '+json.dumps(self.report))
            return rows
        except Exception as e:
            self._emit('error',company=self.company_name,message=str(e));raise RuntimeError(self.company_name+': '+str(e)) from e

    def _take(self,rows,output):
        for j in rows:
            if j['id'] in self._existing or any(r['id']==j['id'] for r in output):continue
            if self._query and self._query not in (j['title']+' '+j['description']).lower():continue
            output.append(j);self._emit('vacancy',**{k:j[k] for k in ('id','title','company','link','locations')})
            if self.limit>0 and len(output)>=self.limit:return True
        return False

    @staticmethod
    def _get(session,url,params):
        for attempt in range(3):
            response=session.get(url,params=params,timeout=30)
            if response.status_code in (429,502,503,504) and attempt<2:time.sleep(1+attempt);continue
            response.raise_for_status();return response.json()

    def _tencent(self):
        import requests
        output=[];page=1;session=requests.Session()
        try:
            while True:
                data=self._get(session,'https://careers.tencent.com/tencentcareer/api/post/Query',{'pageIndex':page,'pageSize':50,'keyword':self._query,'language':'en-us'})
                if data.get('Code')!=200 or not isinstance(data.get('Data',{}).get('Posts'),list):raise ValueError('Tencent: список вакансий не распознан.')
                rows=data['Data']['Posts'];self.report['listed']+=len(rows)
                for j in rows:
                    vid=str(j.get('PostId',''))
                    if not re.fullmatch(r'\d{1,25}',vid):continue
                    url='https://careers.tencent.com/en-us/jobdesc.html?postId='+vid
                    if identity(url)['id'] in self._existing:continue
                    detail=self._get(session,'https://careers.tencent.com/tencentcareer/api/post/ByPostId',{'postId':vid,'language':'en-us'})
                    d=detail.get('Data') or {}
                    if detail.get('Code')!=200 or str(d.get('PostId'))!=vid:raise ValueError('Tencent: другая или отсутствующая карточка.')
                    desc='\n\n'.join(v for v in [clean(d.get('Responsibility')),clean(d.get('Requirement'))] if v)
                    locations=[d.get('LocationName') or j.get('LocationName','')]
                    r=row(self.source_key,url,d.get('RecruitPostName',''),desc,locations,full=bool(d.get('Responsibility') and d.get('Requirement')))
                    if r and self._take([r],output):self.report['coverage']='limited';return output
                    time.sleep(.15)
                if not rows or page*50>=data['Data'].get('Count',page*50):self.report['coverage']='listing_exhausted';return output
                page+=1
        finally:session.close()

    def _kuaishou(self):
        import requests
        output=[];page=1;session=requests.Session()
        try:
            while True:
                data=self._get(session,'https://zhaopin.kuaishou.cn/recruit/e/api/v1/open/positions/simple',{'pageNum':page,'pageSize':50,'positionNatureCode':'C001','recruitProject':'socialr'})
                rows,total=parse_feed(self.source_key,data,CHINA_SOURCES[self.source_key]['url']);self.report['listed']+=len(rows)
                if self._take(rows,output):self.report['coverage']='limited';return output
                if not rows or total is not None and page*50>=total:self.report['coverage']='listing_exhausted';return output
                page+=1;time.sleep(.3)
        finally:session.close()

    def _browser(self):
        from playwright.sync_api import sync_playwright
        spec=CHINA_SOURCES[self.source_key];output=[];feed=[];total=None;seen=set()
        with sync_playwright() as p:
            browser=_launch_browser(p,self.headless);context=browser.new_context();page=context.new_page()
            def capture(response):
                nonlocal total
                if spec['provider']!='feishu' or '/api/v1/search/job/posts' not in response.url or response.status!=200:return
                try:
                    rows,count=parse_feed(self.source_key,response.json(),spec['url']);feed.extend(rows)
                    if count is not None:total=count
                except Exception:self.report['errors']+=1
            page.on('response',capture)
            try:
                response=page.goto(spec['url'],wait_until='domcontentloaded',timeout=45000)
                if response and response.status>=400:raise ValueError('Портал недоступен: HTTP '+str(response.status))
                page.wait_for_timeout(6000)
                for pass_number in range(1000):
                    if re.search(r'/login|/authwall|/checkpoint',page.url) or page.locator('iframe[src*="captcha"],input[type="password"]').count():raise ValueError('Нужен ручной вход или проверка сайта.')
                    if spec['provider']=='feishu':
                        current=list(feed);feed.clear()
                    else:
                        current=[]
                        for a in page.locator('a[href]').evaluate_all('els=>els.map(a=>({url:a.href,text:a.innerText}))'):
                            if not re.search(r'#/?job/[\w-]+|/position/\d+/detail|[?&](?:positionId|postId)=',a['url']):continue
                            own=identity(a['url'])
                            if not own or own['id'] in seen:continue
                            seen.add(own['id'])
                            if own['id'] in self._existing:continue
                            detail=context.new_page()
                            try:
                                detail.goto(a['url'],wait_until='domcontentloaded',timeout=40000);detail.get_by_text('职位描述',exact=True).first.wait_for(state='attached',timeout=12000)
                                data=moka_detail(detail.content(),detail.url);title=data['title'] or a['text'].split('\n')[0]
                                r=row(self.source_key,a['url'],title,data['description'],data['locations'],full=bool(data['description']))
                                if not r or r['description_quality']!='full':raise ValueError('Не распознано полное описание Moka.')
                                current.append(r)
                            except Exception as error:
                                self.report['errors']+=1;print(self.company_name+': detail not read: '+str(error)[:160],flush=True)
                            finally:detail.close()
                            if self.limit>0 and len(current)+len(output)>=self.limit:break
                    self.report['listed']+=len(current)
                    if self._take(current,output):self.report['coverage']='limited';return output
                    next_button=page.locator('li.atsx-pagination-next:not(.atsx-pagination-disabled),li.ant-pagination-next:not(.ant-pagination-disabled),button[aria-label="Next page"]:not([disabled]),button[aria-label="下一页"]:not([disabled])')
                    if next_button.count()==1:
                        next_button.click(timeout=5000);page.wait_for_timeout(1200);continue
                    self.report['coverage']='listing_exhausted' if total is not None and self.report['listed']>=total or self.source_key=='deepseek' and seen else 'partial'
                    break
                if not output and not seen and not self.report['listed'] and total!=0:raise ValueError('Выдача не распознана. Пустой список не подтверждён; проверьте адрес портала или доступ.')
                return output
            finally:context.close();browser.close()


CHINA_SCRAPERS={key:type(''.join(part.title() for part in key.split('_'))+'Scraper',(ChinaScraper,),{'source_key':key,'company_name':spec['label'],'id_prefix':key}) for key,spec in CHINA_SOURCES.items()}
