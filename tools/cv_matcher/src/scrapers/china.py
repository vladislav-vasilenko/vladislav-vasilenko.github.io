"""Public China employer adapters. No login, CAPTCHA bypass, LLM or form submission.

Feishu/ByteDance read the responses generated by normal page navigation and
pagination. Moka reads rendered DOM (its opaque API payload is not decoded).
Tencent and Kuaishou use the public JSON endpoints observed on their job boards.
"""
